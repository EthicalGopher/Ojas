#!/usr/bin/env node
// Embeds backend/Pose/warrior_pose/web/warrior2_engine.js into the app so the
// camera WebView can run the exact same Warrior II geometry engine.
// Run after editing the engine: `make warrior2-engine`
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'backend/Pose/warrior_pose/web/warrior2_engine.js'), 'utf8');
if (src.includes('</script')) throw new Error('engine source must not contain </script');

const out = path.join(root, 'src/features/camera/poseEngines/warrior2EngineSource.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/gen-warrior2-engine.js from\n' +
    '// backend/Pose/warrior_pose/web/warrior2_engine.js. Do not edit by hand.\n' +
    `export const WARRIOR2_ENGINE_SOURCE = ${JSON.stringify(src)};\n`
);
console.log('wrote', path.relative(root, out));
